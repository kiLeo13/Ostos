CREATE TABLE shopping_list_items (
    id BIGINT NOT NULL,
    family_id BIGINT NOT NULL,
    name VARCHAR(160) NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    unit ENUM('each', 'g', 'kg', 'ml', 'l') NOT NULL,
    note VARCHAR(500) NULL,
    is_checked BOOLEAN NOT NULL DEFAULT FALSE,
    purchased_quantity DECIMAL(12,3) NULL,
    total_cents BIGINT NULL,
    position BIGINT NOT NULL,
    added_by_id BIGINT NOT NULL,
    updated_by_id BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_shopping_list_items_family_pos (family_id, position, id),
    CONSTRAINT fk_shopping_list_items_family FOREIGN KEY (family_id) REFERENCES families (id) ON DELETE CASCADE,
    CONSTRAINT fk_shopping_list_items_added_by FOREIGN KEY (added_by_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_shopping_list_items_updated_by FOREIGN KEY (updated_by_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_shopping_list_items_id_positive CHECK (id > 0),
    CONSTRAINT chk_shopping_list_items_name CHECK (CHAR_LENGTH(name) BETWEEN 1 AND 160),
    CONSTRAINT chk_shopping_list_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_shopping_list_items_note CHECK (note IS NULL OR CHAR_LENGTH(note) <= 500),
    CONSTRAINT chk_shopping_list_items_purchased_qty CHECK (purchased_quantity IS NULL OR purchased_quantity > 0),
    CONSTRAINT chk_shopping_list_items_total_cents CHECK (total_cents IS NULL OR total_cents >= 0),
    CONSTRAINT chk_shopping_list_items_position CHECK (position >= 0)
) ENGINE=InnoDB;

CREATE TABLE shopping_trips (
    id BIGINT NOT NULL,
    family_id BIGINT NOT NULL,
    supermarket_name VARCHAR(120) NULL,
    completed_by_id BIGINT NOT NULL,
    completed_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_shopping_trips_family_completed (family_id, completed_at, id),
    KEY idx_shopping_trips_family_id (family_id, id),
    CONSTRAINT fk_shopping_trips_family FOREIGN KEY (family_id) REFERENCES families (id) ON DELETE CASCADE,
    CONSTRAINT fk_shopping_trips_completed_by FOREIGN KEY (completed_by_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_shopping_trips_id_positive CHECK (id > 0),
    CONSTRAINT chk_shopping_trips_supermarket CHECK (supermarket_name IS NULL OR CHAR_LENGTH(supermarket_name) BETWEEN 1 AND 120)
) ENGINE=InnoDB;

CREATE TABLE shopping_trip_items (
    id BIGINT NOT NULL,
    trip_id BIGINT NOT NULL,
    source_item_id BIGINT NOT NULL,
    name VARCHAR(160) NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    unit ENUM('each', 'g', 'kg', 'ml', 'l') NOT NULL,
    note VARCHAR(500) NULL,
    added_by_id BIGINT NOT NULL,
    purchased_quantity DECIMAL(12,3) NULL,
    total_cents BIGINT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_shopping_trip_items_trip (trip_id, id),
    CONSTRAINT fk_shopping_trip_items_trip FOREIGN KEY (trip_id) REFERENCES shopping_trips (id) ON DELETE CASCADE,
    CONSTRAINT fk_shopping_trip_items_added_by FOREIGN KEY (added_by_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_shopping_trip_items_id_positive CHECK (id > 0),
    CONSTRAINT chk_shopping_trip_items_source_id_positive CHECK (source_item_id > 0),
    CONSTRAINT chk_shopping_trip_items_name CHECK (CHAR_LENGTH(name) BETWEEN 1 AND 160),
    CONSTRAINT chk_shopping_trip_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_shopping_trip_items_note CHECK (note IS NULL OR CHAR_LENGTH(note) <= 500),
    CONSTRAINT chk_shopping_trip_items_purchased_qty CHECK (purchased_quantity IS NULL OR purchased_quantity > 0),
    CONSTRAINT chk_shopping_trip_items_total_cents CHECK (total_cents IS NULL OR total_cents >= 0)
) ENGINE=InnoDB;
